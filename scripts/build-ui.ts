// Builds src/ui/page.gen.ts: the page the server serves. PAGE is shell.html (a few hundred bytes); ASSETS are the stylesheet (the Astryx stylesheets, pruned to the
// classes the bundle uses, and fonts + style.css) and the script (the src/ui modules bundled for the browser), each named by a hash of its text, so the browser
// keeps them until a build changes them.
//   bun run ui            write src/ui/page.gen.ts
//   bun run ui --check    exit 1 when src/ui/page.gen.ts differs from a fresh build (tests/launchers.ts runs it)
// Bundler output can differ between Bun versions, so the committed file is the build of PINNED_BUN; a failing --check names it.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COMPRESSORS, EQ_PRESETS } from "../src/audiofx.ts";
import { GRADE_FIELDS, LOOKS } from "../src/color.ts";
import { LIBRARY } from "../src/library.ts";
import { TEMPLATES } from "../src/presets.ts";
import * as M from "../src/model.ts";

/** The inspector form's tables, from the model's own: each section's fields once ([json types, doc]), the sections and keys each clip type has (fieldsFor), and the value lists of the fields that name one. */
const SECTIONS: [string, Record<string, [string[], string]>][] = [["clip", M.COMMON_FIELDS], ["layer", M.VISUAL_FIELDS], ["media", M.MEDIA_FIELDS], ["audio", M.AUDIO_FX_FIELDS],
  ["text", M.TEXT_FIELDS], ["captions", M.CAPTION_FIELDS], ["shape", M.SHAPE_FIELDS], ["color", M.COLOR_FIELDS], ["lottie", M.LOTTIE_FIELDS], ["compound", M.COMPOUND_FIELDS]];
const FORM = {
  fields: Object.fromEntries(SECTIONS),
  types: Object.fromEntries(M.CLIP_TYPES.map((t) => { const has = M.fieldsFor(t), seen = new Set<string>(); return [t, SECTIONS.map(([n, f]) => [n, Object.keys(f).filter((k) => k in has && !seen.has(k) && seen.add(k))]).filter(([, ks]) => ks.length)]; })),
  enums: { position: M.POSITIONS, blend: M.BLENDS, fit: M.FITS, stem: M.STEMS, align: ["left", "center", "right"], style: M.CAPTION_STYLES, shape: M.SHAPES, enter: M.ENTER_EXIT, exit: M.ENTER_EXIT,
    transition: M.TRANSITIONS, motion: M.MOTIONS, eq: Object.keys(EQ_PRESETS), compressor: Object.keys(COMPRESSORS), look: Object.keys(LOOKS) },
  grade: Object.entries(GRADE_FIELDS).filter(([, [t]]) => t.length === 1 && (t[0] === "number" || t[0] === "string")).map(([k, [, doc]]) => [k, doc]),
};

export const PINNED_BUN = "1.4.5";
const ui = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "ui");
const nm = join(ui, "..", "..", "node_modules");

/** The design system's stylesheets in their cascade order (fonts, reset, components, theme), then the page's own (unlayered, so it wins).
 *  The theme's font files are inlined as data URLs. astryx.css holds every component's atomic classes, one rule per line: a line whose classes the
 *  bundle never names is dropped (StyleX writes each class name into the bundle as a literal; a line with no class, :root or an at-rule head is kept). */
export function pageCss(js: string): string {
  const theme = join(nm, "@astryxdesign", "theme-neutral");
  const fonts = readFileSync(join(theme, "fonts.css"), "utf8")
    .replace(/url\('\.\/fonts\/([\w.-]+\.woff2)'\)/g, (_, f: string) => `url(data:font/woff2;base64,${readFileSync(join(theme, "fonts", f)).toString("base64")})`);
  const astryx = readFileSync(join(nm, "@astryxdesign", "core", "dist", "astryx.css"), "utf8").split("\n").filter((l) => {
    const cls = [...l.matchAll(/\.(x[a-z0-9]+)/g)].map((m) => m[1]);
    return !cls.length || l.includes(":root") || cls.some((c) => js.includes(c));
  }).join("\n");
  return [fonts, readFileSync(join(nm, "@astryxdesign", "core", "src", "reset.css"), "utf8"), astryx, readFileSync(join(theme, "dist", "theme.css"), "utf8"), readFileSync(join(ui, "style.css"), "utf8")].join("\n");
}

/** an asset's name: its kind and a hash of its text, so a changed file is a new URL */
const assetName = (text: string, ext: string) => "app." + createHash("sha256").update(text).digest("hex").slice(0, 12) + ext;

/** the shell with its {{STYLE}} and {{SCRIPT}} replaced by the assets' URLs */
export const assemble = (shell: string, css: string, js: string): string =>
  shell.replace(/\{\{(STYLE|SCRIPT)\}\}/g, (_, k: string) => "/assets/" + (k === "STYLE" ? css : js));

/** one JSON.stringify'd line per source line, so a diff reads line by line */
const lines = (text: string) => `[\n${text.split("\n").map((l) => `  ${JSON.stringify(l)},`).join("\n")}\n].join("\\n")`;

/** the module text: the page and its assets by name */
export const pageModule = (page: { html: string; assets: Record<string, string> }): string =>
  `// GENERATED by scripts/build-ui.ts (bun run ui) with Bun ${PINNED_BUN} from the files in src/ui. Do not edit by hand.\n`
  + `// tests/launchers.ts fails when this file differs from a fresh build.\n`
  + `export const PAGE = ${lines(page.html)};\n`
  + `export const ASSETS: Record<string, string> = {\n${Object.entries(page.assets).map(([k, v]) => `  ${JSON.stringify(k)}: ${lines(v)},`).join("\n")}\n};\n`;

export async function buildPage(): Promise<{ html: string; assets: Record<string, string> }> {
  // the bundle names each module in a comment, relative to the working dir: build from the repo root so the text does not depend on where it is run from
  const from = process.cwd();
  process.chdir(join(ui, "..", ".."));
  const res = await Bun.build({
    entrypoints: [join(ui, "main.tsx")], target: "browser", format: "iife", minify: true, sourcemap: "none",
    define: { "process.env.NODE_ENV": '"production"', ENUM: JSON.stringify({ animatable: M.ANIMATABLE, easings: M.EASINGS }), FORM: JSON.stringify(FORM), LIB: JSON.stringify(LIBRARY),
      TPL: JSON.stringify(Object.fromEntries(Object.entries(TEMPLATES).map(([k, v]) => [k, { doc: v.doc, args: v.args }]))) },
  }).finally(() => process.chdir(from));
  if (!res.success) throw new Error(res.logs.map(String).join("\n"));
  const js = '"use strict";\n' + (await res.outputs[0].text()).trim(), css = pageCss(js).trimEnd();
  const jsName = assetName(js, ".js"), cssName = assetName(css, ".css");
  return { html: assemble(readFileSync(join(ui, "shell.html"), "utf8"), cssName, jsName), assets: { [cssName]: css, [jsName]: js } };
}

if (import.meta.main) {
  const text = pageModule(await buildPage()), file = join(ui, "page.gen.ts");
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== text) {
      console.error(`src/ui/page.gen.ts is stale: it differs from a fresh build (reference build: Bun ${PINNED_BUN}; this run: Bun ${Bun.version}). Run: bun run ui`);
      process.exit(1);
    }
  } else {
    writeFileSync(file, text);
    if (Bun.version !== PINNED_BUN) console.error(`note: built with Bun ${Bun.version}; the reference build is Bun ${PINNED_BUN}`);
  }
}
