// Builds src/ui/page.gen.ts: the page (shell.html + style.css + the src/ui modules bundled for the browser) as one string the server serves.
//   bun run ui            write src/ui/page.gen.ts
//   bun run ui --check    exit 1 when src/ui/page.gen.ts differs from a fresh build (tests/launchers.ts runs it)
// Bundler output can differ between Bun versions, so the committed file is the build of PINNED_BUN; a failing --check names it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { COMPRESSORS, EQ_PRESETS } from "../src/audiofx.ts";
import { GRADE_FIELDS, LOOKS } from "../src/color.ts";
import { LIBRARY } from "../src/library.ts";
import * as M from "../src/model.ts";

/** The inspector form's tables, from the model's own: each section's fields once ([json types, doc]), the sections and keys each clip type has (fieldsFor), and the value lists of the fields that name one. */
const SECTIONS: [string, Record<string, [string[], string]>][] = [["clip", M.COMMON_FIELDS], ["layer", M.VISUAL_FIELDS], ["media", M.MEDIA_FIELDS], ["audio", M.AUDIO_FX_FIELDS],
  ["text", M.TEXT_FIELDS], ["captions", M.CAPTION_FIELDS], ["shape", M.SHAPE_FIELDS], ["color", M.COLOR_FIELDS], ["lottie", M.LOTTIE_FIELDS], ["compound", M.COMPOUND_FIELDS]];
const FORM = {
  fields: Object.fromEntries(SECTIONS),
  types: Object.fromEntries(M.CLIP_TYPES.map((t) => { const has = M.fieldsFor(t), seen = new Set<string>(); return [t, SECTIONS.map(([n, f]) => [n, Object.keys(f).filter((k) => k in has && !seen.has(k) && seen.add(k))]).filter(([, ks]) => ks.length)]; })),
  enums: { position: M.POSITIONS, blend: M.BLENDS, fit: M.FITS, stem: M.STEMS, align: ["left", "center", "right"], style: M.CAPTION_STYLES, shape: M.SHAPES, enter: M.ENTER_EXIT, exit: M.ENTER_EXIT,
    transition: M.TRANSITIONS, motion: M.MOTIONS, eq: Object.keys(EQ_PRESETS), compressor: Object.keys(COMPRESSORS), look: Object.keys(LOOKS) },
  grade: Object.entries(GRADE_FIELDS).filter(([, [t]]) => t.length === 1 && (t[0] === "number" || t[0] === "string")).map(([k, [, doc]]) => [k, doc]),
};

export const PINNED_BUN = "1.4.5";
const ui = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "ui");

/** Script text to put between <script> and </script>: `</script` ends the element and `<!--` changes how the rest parses.
 *  `<\/` means the same as `</` in a string, template, regex or comment, and `<\!` means the same as `<!` in a string, template, comment or a regex without the u or v flag.
 *  It does not hold for `<!--` in code position or inside a u/v-flag regex; the page's own sources (src/ui, bundled unminified) have neither. */
export const inlineScript = (js: string): string => js.replace(/<\/(script)/gi, "<\\/$1").replace(/<!--/g, "<\\!--");

/** the shell with its {{STYLE}} and {{SCRIPT}} replaced in one pass (a function replacement: the bundle holds `$` sequences) */
export const assemble = (shell: string, css: string, js: string): string =>
  shell.replace(/\{\{(STYLE|SCRIPT)\}\}/g, (_, k: string) => (k === "STYLE" ? css.trimEnd() : '"use strict";\n' + inlineScript(js.trim())));

/** the module text: one JSON.stringify'd line of the page per source line, so a diff of the bundle reads line by line */
export const pageModule = (page: string): string =>
  `// GENERATED by scripts/build-ui.ts (bun run ui) with Bun ${PINNED_BUN} from the files in src/ui. Do not edit by hand.\n`
  + `// tests/launchers.ts fails when this file differs from a fresh build.\n`
  + `export const PAGE = [\n${page.split("\n").map((l) => `  ${JSON.stringify(l)},`).join("\n")}\n].join("\\n");\n`;

export async function buildPage(): Promise<string> {
  // the bundle names each module in a comment, relative to the working dir: build from the repo root so the text does not depend on where it is run from
  const from = process.cwd();
  process.chdir(join(ui, "..", ".."));
  const res = await Bun.build({
    entrypoints: [join(ui, "main.tsx")], target: "browser", format: "iife", minify: false, sourcemap: "none",
    define: { ENUM: JSON.stringify({ animatable: M.ANIMATABLE, easings: M.EASINGS }), FORM: JSON.stringify(FORM), LIB: JSON.stringify(LIBRARY) },
  }).finally(() => process.chdir(from));
  if (!res.success) throw new Error(res.logs.map(String).join("\n"));
  return assemble(readFileSync(join(ui, "shell.html"), "utf8"), readFileSync(join(ui, "style.css"), "utf8"), await res.outputs[0].text());
}

if (import.meta.main) {
  const text = pageModule(await buildPage()), file = join(ui, "page.gen.ts");
  if (process.argv.includes("--check")) {
    if (readFileSync(file, "utf8") !== text) {
      console.error(`src/ui/page.gen.ts is stale: it differs from a fresh build (reference build: Bun ${PINNED_BUN}; this run: Bun ${Bun.version}). Run: bun run ui`);
      process.exit(1);
    }
  } else {
    writeFileSync(file, text);
    if (Bun.version !== PINNED_BUN) console.error(`note: built with Bun ${Bun.version}; the reference build is Bun ${PINNED_BUN}`);
  }
}
